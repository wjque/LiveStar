"""Sweep LiveStar gate thresholds on dev and validate the selected threshold on val.

The script evaluates the fine-tuned gate head as a binary classifier over the
prepared EgoProactive SFT JSONL splits generated by
``livestar/train/prepare_egoproactive_sft.py``. It runs the model once per split
to cache gate probabilities, sweeps thresholds on dev, then reports val metrics
for the selected threshold(s).
"""

